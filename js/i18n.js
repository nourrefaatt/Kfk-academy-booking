let lang = 'en';
try { lang = localStorage.getItem('kfk_lang') || 'en'; } catch { lang = 'en'; }

export function getLang() { return lang; }
export function setLang(l) {
  lang = l === 'ar' ? 'ar' : 'en';
  try { localStorage.setItem('kfk_lang', lang); } catch {}
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
}
export function t(key, vars = {}) {
  let s = dict[lang][key] ?? dict.en[key] ?? key;
  if (typeof s === 'string') for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}
export function tErr(err) {
  let msg = (err && (err.message || err.error_description)) || String(err);
  if (lang === 'ar') {
    for (const [en, ar] of Object.entries(errorsAr)) if (msg.startsWith(en)) return ar;
    if (msg.startsWith('Weekly limit reached')) return 'وصلت للحد الأسبوعي.';
  }
  return msg;
}
